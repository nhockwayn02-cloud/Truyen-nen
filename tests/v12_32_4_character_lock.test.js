// V12.32.4: HỒ SƠ KHÓA — prompt viết, Review (profileViolation = lỗi nặng), Rewrite.
const fs=require('fs'),vm=require('vm'),path=require('path'),assert=require('assert');
const core=fs.readFileSync(path.join(__dirname,'../shared/core.js'),'utf8');
const sb={console};vm.createContext(sb);
vm.runInContext(core+'\n;Object.assign(this,{characterLockPrompt,lockCharsForText,evaluateReview,buildQualityReviewPrompt,buildRewritePrompt,GATE_REVIEW_SCHEMA,storyControlPrompt});',sb);
const mc={name:'Hùng',occupation:'nhân viên bảo vệ',age:'28',speech:'giản dị, lễ phép với cấp trên'};
const st={mainCharProfile:mc,characters:[{id:'a',name:'Lan',occupation:'giám đốc',position:'chủ tịch công ty'},{id:'b',name:'Minh',occupation:'lái xe'}]};
const chars=sb.lockCharsForText(st,'Lan nói chuyện với Hùng.');
assert.strictEqual(JSON.stringify(chars.map(c=>c.name)),'["Lan"]','chỉ nhân vật có mặt trong văn bản');
const full=sb.characterLockPrompt(mc,chars,false);
assert(/nghề: nhân viên bảo vệ/.test(full)&&/chủ tịch công ty/.test(full)&&/không tự nâng cấp/i.test(full),'khối đầy đủ có hồ sơ + luật');
const short=sb.characterLockPrompt(mc,chars,true);
assert(short.length<full.length&&/nhân viên bảo vệ/.test(short),'bản ngắn vẫn có hồ sơ');
assert.strictEqual(sb.characterLockPrompt({}, [], false),'', 'không có hồ sơ -> rỗng');
assert(/profileViolation/.test(sb.GATE_REVIEW_SCHEMA),'schema có profileViolation');
const rv=sb.evaluateReview({score:98,verdict:'PASS',profileViolation:true,profileViolations:['Hùng nói "công ty của tao" — nghề bảo vệ']},{});
assert.strictEqual(rv.verdict,'HARD_FAIL','vi phạm hồ sơ = lỗi nặng');
assert(rv.hardFailures.some(x=>/công ty của tao/.test(x)),'ghi lý do cụ thể');
assert.strictEqual(sb.evaluateReview({score:98},{}).verdict,'PASS','không vi phạm thì vẫn PASS');
const lock=sb.characterLockPrompt(mc,chars,true);
assert(sb.buildQualityReviewPrompt({characterLock:lock,draft:'x'}).includes('HỒ SƠ KHÓA')&&/profileViolation=true CHỈ KHI/.test(sb.buildQualityReviewPrompt({characterLock:lock,draft:'x'})),'review prompt có khối khóa + luật');
assert(!/profileViolation=true CHỈ KHI/.test(sb.buildQualityReviewPrompt({draft:'x'})),'không có hồ sơ thì không thêm luật');
assert(sb.buildRewritePrompt({chapterNumber:1,characterLock:lock,draft:'x'}).includes('HỒ SƠ KHÓA'),'rewrite có khối khóa');
assert(/KHÔNG áp dụng cho địa vị/.test(sb.storyControlPrompt({})),'siết câu ĐƯỢC TỰ DO');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
assert(/characterLockPromptClient\(false\)/.test(html)&&(html.match(/characterLockPromptClient\(true\)/g)||[]).length>=3,'prompt viết + 3 prompt viết tiếp');
console.log('PASS V12.32.4 character lock');
